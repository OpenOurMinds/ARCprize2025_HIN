class Sampling(layers.Layer):
    """Uses (z_mean, z_log_var) to sample z, the vector encoding a digit."""
    def call(self, inputs):
        z_mean, z_log_var = inputs
        batch = tf.shape(z_mean)[0]
        dim = tf.shape(z_mean)[1]
        # Use tf.random.normal directly, it should work within a Layer's call method
        epsilon = tf.random.normal(shape=(batch, dim))
        return z_mean + tf.exp(0.5 * z_log_var) * epsilon


class Encoder(Model):
    """The encoder component of the D-VAE."""
    def __init__(self, latent_dim, grid_size, name='encoder', **kwargs):
        # Call super().__init__ first for subclassed part
        super(Encoder, self).__init__(name=name, **kwargs)
        self.latent_dim = latent_dim
        self.grid_size = grid_size

        # Define the input layer explicitly for the Functional Model build
        inputs = layers.Input(shape=(self.grid_size, self.grid_size, 1), dtype=tf.float32)

        x = layers.Conv2D(32, 3, activation='relu', strides=2, padding='same', kernel_initializer=GlorotNormal())(inputs)
        x = layers.BatchNormalization()(x)
        x = layers.Conv2D(64, 3, activation='relu', strides=2, padding='same', kernel_initializer=GlorotNormal())(x)
        x = layers.BatchNormalization()(x)
        x = layers.Flatten()(x)
        z_mean = layers.Dense(self.latent_dim, name='z_mean')(x)
        z_log_var = layers.Dense(self.latent_dim, name='z_log_var')(x)

        # Build the Functional Model by calling super().__init__ again with inputs/outputs
        super(Encoder, self).__init__(inputs=inputs, outputs=[z_mean, z_log_var], name=name)


class Decoder(Model):
    """The decoder component of the D-VAE."""
    def __init__(self, latent_dim, num_colors, grid_size, name='decoder', **kwargs):
        # Call super().__init__ first for subclassed part
        super(Decoder, self).__init__(name=name, **kwargs)
        self.num_colors = num_colors
        self.latent_dim = latent_dim
        self.grid_size = grid_size

        initial_h = grid_size // 4
        initial_w = grid_size // 4

        # Define the input layer explicitly for the Functional Model build (latent space vector)
        inputs = layers.Input(shape=(self.latent_dim,), dtype=tf.float32)

        x = layers.Dense(initial_h * initial_w * 16, activation='relu')(inputs)
        x = layers.Reshape((initial_h, initial_w, 16))(x)

        x = layers.Conv2DTranspose(64, 3, activation='relu', strides=2, padding='same', kernel_initializer=GlorotNormal())(x)
        x = layers.BatchNormalization()(x)
        x = layers.Conv2DTranspose(32, 3, activation='relu', strides=2, padding='same', kernel_initializer=GlorotNormal())(x)
        x = layers.BatchNormalization()(x)

        outputs = layers.Conv2DTranspose(self.num_colors, 3, activation='softmax', padding='same', kernel_initializer=GlorotNormal())(x)

        # Build the Functional Model by calling super().__init__ again with inputs/outputs
        super(Decoder, self).__init__(inputs=inputs, outputs=outputs, name=name)


class DVAE(Model):
    """The complete VAE model, with encoder and decoder."""
    def __init__(self, latent_dim, num_colors, grid_size, **kwargs):
        super(DVAE, self).__init__(**kwargs)
        self.latent_dim = latent_dim
        self.num_colors = num_colors
        self.grid_size = grid_size

        # Instantiate Encoder and Decoder as sub-models
        # Pass the grid_size to the Encoder during instantiation
        self.encoder = Encoder(latent_dim=latent_dim, grid_size=grid_size)
        self.decoder = Decoder(latent_dim=latent_dim, num_colors=num_colors, grid_size=grid_size)
        self.sampling = Sampling() # Instantiate the Sampling layer

        # The model structure will be defined in the call method
        # No need to build the functional model if overriding call

    def call(self, inputs):
        # Cast input to float32 if it's not already
        inputs_f32 = tf.cast(inputs, dtype=tf.float32)

        z_mean, z_log_var = self.encoder(inputs_f32)
        z = self.sampling([z_mean, z_log_var])
        reconstruction = self.decoder(z)

        # Add the KL divergence loss within the call method
        # This ensures that the loss is calculated using the symbolic tensors
        kl_loss = -0.5 * tf.reduce_sum(1 + z_log_var - tf.square(z_mean) - tf.exp(z_log_var), axis=1)
        self.add_loss(tf.reduce_mean(kl_loss))

        return reconstruction


