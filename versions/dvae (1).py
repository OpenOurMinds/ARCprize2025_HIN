class BaseDataLoader:
    """Base class for creating a tf.data.Dataset pipeline."""
    def __init__(self, config):
        self.config = config

    def _pad_grid_tf(self, grid_tensor):
        """Pads a grid tensor with zeros to a fixed size."""
        height, width = tf.shape(grid_tensor)[0], tf.shape(grid_tensor)[1]
        padded_grid = tf.pad(
            grid_tensor,
            [[0, self.config.grid_size - height], [0, self.config.grid_size - width]],
            constant_values=0 # Use 0 for padding as it is a valid color and a safe background
        )
        return tf.cast(padded_grid, dtype=tf.int32)

    def _get_data_generator(self):
        """Placeholder for a generator function, implemented by subclasses."""
        raise NotImplementedError("Subclasses must implement _get_data_generator.")

    def load_dataset(self):
        """Returns a batched, pre-processed tf.data.Dataset."""
        generator = self._get_data_generator()
        ds = tf.data.Dataset.from_generator(
            generator,
            output_signature=tf.TensorSpec(shape=(None, None), dtype=tf.int32) # Keep shape as None initially
        )

        ds = ds.map(self._pad_grid_tf, num_parallel_calls=tf.data.AUTOTUNE)
        ds = ds.map(lambda x: tf.expand_dims(x, axis=-1), num_parallel_calls=tf.data.AUTOTUNE)

        # Set the shape explicitly after padding and expanding dimensions
        ds = ds.map(lambda x: tf.ensure_shape(x, (self.config.grid_size, self.config.grid_size, 1)))

        ds = ds.shuffle(buffer_size=5000)
        ds = ds.batch(self.config.batch_size)
        ds = ds.prefetch(tf.data.AUTOTUNE)
        return ds


class ARCDataLoader(BaseDataLoader):
    """Data loader for the official ARC challenges."""
    def _get_data_generator(self):
        def generator():
            try:
                with open(self.config.training_challenges_path, 'r') as f:
                    full_data = json.load(f)
            except FileNotFoundError:
                logging.error(f"ARC training challenges file not found at: {self.config.training_challenges_path}")
                return

            for task_data in full_data.values():
                for example in task_data['train']:
                    if 'output' in example and example['output']:
                        output_grid = np.array(example['output'], dtype=np.int32)
                        yield output_grid
        return generator

class SyntheticDataLoader(BaseDataLoader):
    """Data loader for GAN-generated synthetic grids."""
    def _get_data_generator(self):
        def generator():
            for path in self.config.synthetic_data_paths:
                try:
                    with open(path, 'r') as f:
                        data = json.load(f)
                        for item in data:
                            if isinstance(item, list):
                                if all(isinstance(sublist, list) for sublist in item):
                                    yield np.array(item, dtype=np.int32)
                                elif all(isinstance(val, (int, float)) for val in item):
                                    grid_size = int(np.sqrt(len(item)))
                                    if grid_size * grid_size == len(item):
                                        yield np.array(item, dtype=np.int32).reshape(grid_size, grid_size)
                except (FileNotFoundError, ValueError, json.JSONDecodeError) as e:
                    logging.warning(f"Skipping file {path} due to error: {e}")
        return generator

# --- D-VAE Model Definition ---
class Encoder(layers.Layer):
    """The encoder component of the D-VAE."""
    def __init__(self, latent_dim, name='encoder', **kwargs):
        super(Encoder, self).__init__(name=name, **kwargs)
        self.conv1 = layers.Conv2D(32, 3, activation='relu', strides=2, padding='same', kernel_initializer=GlorotNormal())
        self.bn1 = layers.BatchNormalization()
        self.conv2 = layers.Conv2D(64, 3, activation='relu', strides=2, padding='same', kernel_initializer=GlorotNormal())
        self.bn2 = layers.BatchNormalization()
        self.flatten = layers.Flatten()
        self.z_mean = layers.Dense(latent_dim, name='z_mean')
        self.z_log_var = layers.Dense(latent_dim, name='z_log_var')

    def call(self, inputs):
        x = self.conv1(inputs)
        x = self.bn1(x)
        x = self.conv2(x)
        x = self.bn2(x)
        x = self.flatten(x)
        z_mean = self.z_mean(x)
        z_log_var = self.z_log_var(x)
        return z_mean, z_log_var

class Decoder(layers.Layer):
    """The decoder component of the D-VAE."""
    def __init__(self, latent_dim, num_colors, grid_size, name='decoder', **kwargs):
        super(Decoder, self).__init__(name=name, **kwargs)
        self.num_colors = num_colors
        self.latent_dim = latent_dim

        initial_h = grid_size // 4
        initial_w = grid_size // 4

        self.dense = layers.Dense(initial_h * initial_w * 16, activation='relu')
        self.reshape = layers.Reshape((initial_h, initial_w, 16))

        self.deconv1 = layers.Conv2DTranspose(64, 3, activation='relu', strides=2, padding='same', kernel_initializer=GlorotNormal())
        self.bn1 = layers.BatchNormalization()
        self.deconv2 = layers.Conv2DTranspose(32, 3, activation='relu', strides=2, padding='same', kernel_initializer=GlorotNormal())
        self.bn2 = layers.BatchNormalization()

        self.output_conv = layers.Conv2DTranspose(num_colors, 3, activation='softmax', padding='same', kernel_initializer=GlorotNormal())

    def call(self, inputs):
        x = self.dense(inputs)
        x = self.reshape(x)
        x = self.deconv1(x)
        x = self.bn1(x)
        x = self.deconv2(x)
        x = self.bn2(x)
        return self.output_conv(x)

class DVAE(Model):
    """The complete VAE model, with encoder and decoder."""
    def __init__(self, latent_dim, num_colors, grid_size, **kwargs):
        super(DVAE, self).__init__(**kwargs)
        self.latent_dim = latent_dim
        self.num_colors = num_colors
        self.grid_size = grid_size

        # Define the input layer explicitly
        self.input_layer = layers.Input(shape=(grid_size, grid_size, 1))

        self.encoder = Encoder(latent_dim)
        self.decoder = Decoder(latent_dim, num_colors, grid_size)

        # Define the model by connecting input and output
        z_mean, z_log_var = self.encoder(self.input_layer)
        z = self._sampling(z_mean, z_log_var)
        reconstruction = self.decoder(z)

        # Build the Keras Model
        super(DVAE, self).__init__(inputs=self.input_layer, outputs=reconstruction, **kwargs)

        # Add the KL divergence loss as an internal loss
        kl_loss = -0.5 * tf.reduce_sum(1 + z_log_var - tf.square(z_mean) - tf.exp(z_log_var), axis=1)
        self.add_loss(tf.reduce_mean(kl_loss))


    def _sampling(self, z_mean, z_log_var):
        epsilon = tf.random.normal(shape=tf.shape(z_mean))
        return z_mean + tf.exp(0.5 * z_log_var) * epsilon

    def call(self, inputs):
        # This call method is now primarily used during inference or custom training loops
        # For standard model.fit, the model is built via the __init__ method with Input layer
        # Cast input to float32 for convolution
        inputs_f32 = tf.cast(inputs, dtype=tf.float32)

        z_mean, z_log_var = self.encoder(inputs_f32)
        z = self._sampling(z_mean, z_log_var)
        reconstruction = self.decoder(z)
        return reconstruction


