# Helper function for Rotary Positional Embedding (RoPE) - simplified
def rotate_half(x):
    x1, x2 = x.chunk(2, dim=-1)
    return torch.cat((-x2, x1), dim=-1)

def apply_rope(x, freqs):
    return (x * freqs.cos()) + (rotate_half(x) * freqs.sin())

# Define the TransformerDiscriminator class (re-defined for this cell)
class TransformerDiscriminator(nn.Module):
    def __init__(self, vocab_size, hidden_size, num_layers, num_heads, max_seq_length, condition_size=0, num_channels=2):
        super(TransformerDiscriminator, self).__init__()
        self.vocab_size = vocab_size
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.num_heads = num_heads
        self.max_seq_length = max_seq_length
        self.condition_size = condition_size
        self.num_channels = num_channels

        self.embedding = nn.Embedding(vocab_size, hidden_size)
        self.positional_embedding = nn.Embedding(max_seq_length, hidden_size)
        self.channel_embedding = nn.Embedding(num_channels, hidden_size)

        if self.condition_size > 0:
             self.condition_linear = nn.Linear(condition_size, hidden_size)

        encoder_layer = nn.TransformerEncoderLayer(d_model=hidden_size, nhead=num_heads, batch_first=True)
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)

        self.fc = nn.Linear(hidden_size, 1)

    def forward(self, x, channel_indices, conditioning=None):
        embedded_tokens = self.embedding(x)
        positions = torch.arange(0, x.size(1)).unsqueeze(0).repeat(x.size(0), 1).to(x.device)
        embedded_positions = self.positional_embedding(positions)
        embedded_channels = self.channel_embedding(channel_indices)

        embedded = embedded_tokens + embedded_positions + embedded_channels

        if conditioning is not None:
            processed_condition = self.condition_linear(conditioning).unsqueeze(1)
            embedded[:, 0, :] = embedded[:, 0, :] + processed_condition[:, 0, :]

        output_sequence = self.transformer_encoder(embedded)
        pooled_output = torch.mean(output_sequence, dim=1)
        score = self.fc(pooled_output)
        probability = torch.sigmoid(score)

        return probability

# Define the TransformerGenerator class (re-defined for this cell)
class TransformerGenerator(nn.Module):
    def __init__(self, vocab_size, hidden_size, num_layers, num_heads, max_seq_length, noise_dim=100, condition_size=0):
        super(TransformerGenerator, self).__init__()
        self.vocab_size = vocab_size
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.num_heads = num_heads
        self.max_seq_length = max_seq_length
        self.noise_dim = noise_dim
        self.condition_size = condition_size

        self.embedding = nn.Embedding(vocab_size, hidden_size)

        freqs = 1.0 / (10000 ** (torch.arange(0, hidden_size, 2).float() / hidden_size))
        self.register_buffer('freqs', freqs.repeat_interleave(2).unsqueeze(0))

        input_linear_size = self.noise_dim + self.condition_size
        self.input_linear = nn.Linear(input_linear_size, hidden_size)

        decoder_layer = nn.TransformerDecoderLayer(d_model=hidden_size, nhead=num_heads, batch_first=True)
        self.transformer_decoder = nn.TransformerDecoder(decoder_layer, num_layers=num_layers)

        self.fc = nn.Linear(hidden_size, vocab_size)

    def forward(self, x, noise, conditioning=None):
        embedded = self.embedding(x)

        seq_len = embedded.size(1)
        freqs_expanded_for_rope = self.freqs[:, :seq_len, :].expand(x.size(0), seq_len, -1)
        embedded = apply_rope(embedded, freqs_expanded_for_rope)

        processed_combined_input = self.input_linear(noise if conditioning is None else torch.cat((noise, conditioning), dim=1))
        processed_combined_input_expanded = processed_combined_input.unsqueeze(1).expand(-1, seq_len, -1)
        embedded = embedded + processed_combined_input_expanded

        causal_mask = torch.triu(torch.ones(seq_len, seq_len) * float('-inf'), diagonal=1).to(x.device)

        output_sequence = self.transformer_decoder(embedded, memory=None, tgt_mask=causal_mask)

        logits = self.fc(output_sequence)

        return logits

