        # Process noise and conditioning
        if conditioning is not None:
            combined_input = torch.cat((noise, conditioning), dim=1)
        else:
            combined_input = noise

        # Pass combined input through linear layer - this output could be used to initialize LSTM state
        # Let's use it to initialize the LSTM hidden and cell states.
        processed_combined_input = self.input_linear(combined_input) # shape: (batch_size, hidden_size)

        # Initialize hidden and cell states
        # For bidirectional LSTM, h0 and c0 should have shape (num_layers * 2, batch_size, hidden_size)
        h0 = processed_combined_input.unsqueeze(0).repeat(self.num_layers * 2, 1, 1)
        c0 = torch.zeros(self.num_layers * 2, x.size(0), self.hidden_size).to(x.device)

