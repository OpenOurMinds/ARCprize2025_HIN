class Generator(nn.Module):
    def __init__(self, input_size, hidden_size, output_size, num_layers=3, noise_dim=100, condition_size=0):
        super(Generator, self).__init__()
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.noise_dim = noise_dim
        self.condition_size = condition_size

        # Embedding layer for the input sequence (grid values and special tokens)
        self.embedding = nn.Embedding(input_size, hidden_size)

        # Linear layer to process the noise vector and potentially conditioning information
        # The input size to this layer will depend on how noise and conditioning are combined
        # A simple approach is to concatenate noise and conditioning and then pass through a linear layer
        input_linear_size = self.noise_dim + self.condition_size
        self.input_linear = nn.Linear(input_linear_size, hidden_size)


        # Stacked Bidirectional LSTM layer(s)
        # Input size is hidden_size (from embedding)
        # Output size of BiLSTM is 2 * hidden_size because it's bidirectional
        self.lstm = nn.LSTM(hidden_size, hidden_size, num_layers, batch_first=True, bidirectional=True)


        # Linear layer to output the sequence
        # The input size to the linear layer will be 2 * hidden_size due to BiLSTM
        self.fc = nn.Linear(hidden_size * 2, output_size) # output_size would be the vocabulary size again

    def forward(self, x, noise, conditioning=None):
        # x is expected to be of shape (batch_size, sequence_length) - the input grid sequence
        # noise is expected to be of shape (batch_size, noise_dim)
        # conditioning is expected to be of shape (batch_size, condition_size) or None

        # Embed the input sequence
        embedded = self.embedding(x) # shape: (batch_size, sequence_length, hidden_size)

        # Process noise and conditioning
        if conditioning is not None:
            combined_input = torch.cat((noise, conditioning), dim=1)
        else:
            combined_input = noise

        # Pass combined input through linear layer - this output could be used to initialize LSTM state
        # or be incorporated differently. For now, let's just process it.
        processed_combined_input = self.input_linear(combined_input) # shape: (batch_size, hidden_size)

        # Pass embedded sequence through LSTM
        # We can potentially use processed_combined_input to initialize the hidden state of the LSTM
        # h0 = processed_combined_input.unsqueeze(0).repeat(self.num_layers * 2, 1, 1) # *2 for bidirectional
        # c0 = torch.zeros(self.num_layers * 2, x.size(0), self.hidden_size).to(x.device) # *2 for bidirectional
        # out, _ = self.lstm(embedded, (h0, c0))

        # For simplicity, let's just pass the embedded sequence through LSTM
        out, _ = self.lstm(embedded) # shape: (batch_size, sequence_length, 2 * hidden_size)


        # Pass through the linear layer to get output predictions
        # We apply the linear layer to each time step
        out = self.fc(out) # shape: (batch_size, sequence_length, output_size)

        return out

