# Helper function for Rotary Positional Embedding (RoPE)
# This is a simplified version; a full RoPE implementation might be more complex
def rotate_half(x):
    x1, x2 = x.chunk(2, dim=-1)
    return torch.cat((-x2, x1), dim=-1)

def apply_rope(x, freqs):
    # x: (batch_size, sequence_length, hidden_size)
    # freqs: (sequence_length, hidden_size)
    # Apply RoPE to the last dimension
    return (x * freqs.cos()) + (rotate_half(x) * freqs.sin())

class TransformerGenerator(nn.Module):
    def __init__(self, vocab_size, hidden_size, num_layers, num_heads, max_seq_length, noise_dim=100, condition_size=0):
        super(TransformerGenerator, self).__init__()
        self.vocab_size = vocab_size
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.num_heads = num_heads
        self.max_seq_length = max_seq_length
        self.noise_dim = noise_dim
        self.condition_size = condition_size

        # Embedding layer
        self.embedding = nn.Embedding(vocab_size, hidden_size)

        # Positional Encoding (Simplified RoPE-like)
        # Generate frequencies for RoPE
        freqs = 1.0 / (10000 ** (torch.arange(0, hidden_size, 2).float() / hidden_size))
        self.register_buffer('freqs', freqs.repeat_interleave(2).unsqueeze(0)) # shape: (1, hidden_size)


        # Linear layer to process noise and conditioning
        input_linear_size = self.noise_dim + self.condition_size
        self.input_linear = nn.Linear(input_linear_size, hidden_size) # Project to hidden_size


        # Transformer Decoder Layers
        # Using PyTorch's TransformerDecoderLayer and TransformerDecoder
        decoder_layer = nn.TransformerDecoderLayer(d_model=hidden_size, nhead=num_heads, batch_first=True)
        self.transformer_decoder = nn.TransformerDecoder(decoder_layer, num_layers=num_layers)

        # Final linear layer to output vocabulary scores
        self.fc = nn.Linear(hidden_size, vocab_size)

    def forward(self, x, noise, conditioning=None):
        # x is expected to be of shape (batch_size, sequence_length) - the input grid sequence
        # noise is expected to be of shape (batch_size, noise_dim)
        # conditioning is expected to be of shape (batch_size, condition_size) or None

        # Embed the input sequence
        embedded = self.embedding(x) # shape: (batch_size, sequence_length, hidden_size)

        # Apply Positional Encoding (RoPE)
        # Need to expand freqs to match sequence length
        freqs = self.freqs[:, :embedded.size(1), :] # shape: (1, sequence_length, hidden_size)
        embedded = apply_rope(embedded, freqs)

        # Process noise and conditioning and potentially use it as initial state or add to embeddings
        # For a Transformer Decoder, we often use a learned query token or cross-attention.
        # A simple way to incorporate noise/conditioning is to add it to the input embeddings
        # after processing it through a linear layer.
        processed_combined_input = self.input_linear(noise if conditioning is None else torch.cat((noise, conditioning), dim=1)) # shape: (batch_size, hidden_size)
        # Expand and add to embeddings (requires careful broadcasting or unsqueezing)
        # Let's try adding to the first token's embedding as a simple approach for now
        # embedded[:, 0, :] = embedded[:, 0, :] + processed_combined_input


        # For a standard Transformer Decoder, we often need a memory or target sequence
        # In an autoregressive setup, the input 'x' serves as both the target and part of the memory
        # We need a causal mask to prevent attending to future tokens in the output sequence portion
        # Assuming x contains [start_token, input_grid, separator_token, output_grid]
        # The causal mask should apply from the separator_token onwards.
        # This requires a more complex mask than a standard causal mask.
        # For simplicity in this initial structure, let's assume a standard causal mask for now.
        # A proper implementation for ARC would need a custom mask.
        seq_len = x.size(1)
        causal_mask = torch.triu(torch.ones(seq_len, seq_len) * float('-inf'), diagonal=1).to(x.device)


        # Pass through Transformer Decoder
        # TransformerDecoder expects target (embedded), memory (can be None if self-attention only)
        # and masks.
        # For autoregressive generation from an input sequence, the input sequence itself
        # acts as the target.
        # We might need a separate "memory" if we have an encoder part, but for a decoder-only Generator,
        # the input sequence is the primary information.

        # Let's use the embedded sequence as the target for the decoder
        output_sequence = self.transformer_decoder(embedded, memory=None, tgt_mask=causal_mask) # shape: (batch_size, sequence_length, hidden_size)


        # Final linear layer
        logits = self.fc(output_sequence) # shape: (batch_size, sequence_length, vocab_size)

        # Softmax to get probabilities (often done in the loss function for numerical stability)
        # probabilities = F.softmax(logits, dim=-1)

        return logits # Return logits for use with CrossEntropyLoss

