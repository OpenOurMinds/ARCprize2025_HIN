class TransformerDiscriminator(nn.Module):
    def __init__(self, vocab_size, hidden_size, num_layers, num_heads, max_seq_length, condition_size=0, num_channels=2):
        super(TransformerDiscriminator, self).__init__()
        self.vocab_size = vocab_size
        self.hidden_size = hidden_size
        self.num_layers = num_layers
        self.num_heads = num_heads
        self.max_seq_length = max_seq_length
        self.condition_size = condition_size
        self.num_channels = num_channels # Number of channels (e.g., input and output)

        # Embedding layer for tokens
        self.embedding = nn.Embedding(vocab_size, hidden_size)

        # Positional Encoding (using learned embeddings)
        self.positional_embedding = nn.Embedding(max_seq_length, hidden_size)

        # Channel Embedding
        self.channel_embedding = nn.Embedding(num_channels, hidden_size)


        # If using conditioning, a linear layer to process it
        if self.condition_size > 0:
             self.condition_linear = nn.Linear(condition_size, hidden_size)


        # Transformer Encoder Layers
        encoder_layer = nn.TransformerEncoderLayer(d_model=hidden_size, nhead=num_heads, batch_first=True)
        self.transformer_encoder = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)

        # Final linear layer to output a single score
        self.fc = nn.Linear(hidden_size, 1)

    def forward(self, x, channel_indices, conditioning=None):
        # x is expected to be of shape (batch_size, sequence_length) - the grid sequence
        # channel_indices is expected to be of shape (batch_size, sequence_length) indicating the channel for each token
        # conditioning is expected to be of shape (batch_size, condition_size) or None

        # Embed tokens
        embedded_tokens = self.embedding(x) # shape: (batch_size, sequence_length, hidden_size)

        # Add positional embedding
        positions = torch.arange(0, x.size(1)).unsqueeze(0).repeat(x.size(0), 1).to(x.device)
        embedded_positions = self.positional_embedding(positions) # shape: (batch_size, sequence_length, hidden_size)

        # Embed channel information
        embedded_channels = self.channel_embedding(channel_indices) # shape: (batch_size, sequence_length, hidden_size)

        # Combine embeddings (summing is a common approach)
        embedded = embedded_tokens + embedded_positions + embedded_channels # shape: (batch_size, sequence_length, hidden_size)


        # Process conditioning and combine with embedded sequence (simple addition to the first token)
        if conditioning is not None:
            processed_condition = self.condition_linear(conditioning).unsqueeze(1) # shape: (batch_size, 1, hidden_size)
            # Simple approach: add to the first token's embedding
            embedded[:, 0, :] = embedded[:, 0, :] + processed_condition[:, 0, :]


        # Pass through Transformer Encoder
        output_sequence = self.transformer_encoder(embedded) # shape: (batch_size, sequence_length, hidden_size)

        # Pool the output sequence to get a single representation per sequence
        pooled_output = torch.mean(output_sequence, dim=1) # shape: (batch_size, hidden_size)

        # Pass through the final linear layer
        score = self.fc(pooled_output) # shape: (batch_size, 1)

        # Apply sigmoid activation to get a probability score
        probability = torch.sigmoid(score)

        return probability

